def apply_admin_labels():
    """Aplica rótulos somente em memória, para apresentação no admin."""
    for model in apps.get_app_config("starrp").get_models():
        labels = MODEL_LABELS.get(model.__name__)
        if labels:
            model._meta.verbose_name, model._meta.verbose_name_plural = labels
        for field in model._meta.fields:
            if field.name in FIELD_LABELS:
                field.verbose_name = FIELD_LABELS[field.name]
    token_app = apps.get_app_config("token_blacklist")
    token_app.verbose_name = "Sessões e segurança"
    token_labels = {
        "BlacklistedToken": ("Token bloqueado", "Tokens bloqueados"),
        "OutstandingToken": ("Token ativo", "Tokens ativos"),
    }
    for model in token_app.get_models():
        if model.__name__ in token_labels:
            model._meta.verbose_name, model._meta.verbose_name_plural = token_labels[model.__name__]
