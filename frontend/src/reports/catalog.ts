export const findReport = (slug: string) => REPORT_GROUPS.flatMap((g) => g.reports.map((r) => ({ ...r, group: g.label })))
  .find((r) => r.slug === slug);

/** Os grupos com só os relatórios que o usuário abre (permissão e módulo). */
export function visibleGroups(can: (code?: string) => boolean, hasModule: (m?: string) => boolean) {
  return REPORT_GROUPS.map((g) => ({ ...g, reports: g.reports.filter((r) => can(r.permission) && hasModule(r.module)) }))
    .filter((g) => g.reports.length);
}
